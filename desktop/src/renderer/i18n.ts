export type MessageKey = keyof typeof en;

let dict: Dict = en;

export function setLanguage(lang: "en" | "zh_CN") {
  dict = lang === "zh_CN" ? zh_CN : en;
  document.documentElement.lang = lang === "zh_CN" ? "zh-CN" : "en";
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = dict[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function timeAgo(ts: number): string {
  const diff = Date.now() - ts;
  if (diff < 60_000) return t("justNow");
  if (diff < 3_600_000) return t("minutesAgo", { n: Math.floor(diff / 60_000) });
  if (diff < 86_400_000) return t("hoursAgo", { n: Math.floor(diff / 3_600_000) });
  return new Date(ts).toLocaleDateString();
}
